export type LabPseudoElement = "::before" | "::after";

interface LabInspectorControlBase {
  readonly id: string;
  readonly groupId: LabInspectorGroupId;
  readonly label: string;
  readonly description: string;
  readonly cssProperty: string;
  readonly computedProperty?: string;
  readonly special?:
    | "translateX"
    | "translateY"
    | "edgeTopOffset"
    | "edgeRightOffset"
    | "edgeBottomOffset"
    | "edgeLeftOffset";
}

export interface LabInspectorNumberControl extends LabInspectorControlBase {
  readonly kind: "number";
  readonly min: number;
  readonly max: number;
  readonly step: number;
  readonly defaultValue: number;
  readonly unit: "px" | "ms" | "deg" | "";
  readonly readAs?: "rectWidth" | "rectHeight" | "milliseconds";
}

export interface LabInspectorSelectControl extends LabInspectorControlBase {
  readonly kind: "select";
  readonly defaultValue: string;
  readonly options: readonly {
    readonly value: string;
    readonly label: string;
  }[];
}

export interface LabInspectorColorControl extends LabInspectorControlBase {
  readonly kind: "color";
  readonly defaultValue: string;
}

export interface LabInspectorTextControl extends LabInspectorControlBase {
  readonly kind: "text";
  readonly defaultValue: string;
  readonly placeholder?: string;
}

export type LabInspectorControl =
  | LabInspectorNumberControl
  | LabInspectorSelectControl
  | LabInspectorColorControl
  | LabInspectorTextControl;

