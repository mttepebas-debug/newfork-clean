export function targetSelector(
  definition: LabTargetDefinition,
  mode: LabMode,
): string {
  const selector = targetElementSelector(definition, mode);
  if (!definition.pseudoElement) return selector;
  return selector
    .split(",")
    .map((part) => `${part.trim()}${definition.pseudoElement}`)
    .join(", ");
}

export function targetElementSelector(
  definition: LabTargetDefinition,
  mode: LabMode,
): string {
  return definition.selectorByMode?.[mode] ?? definition.selector;
}

export function stateDefinition(stateId: LabStateId): LabStateDefinition {
  return labStates.find((item) => item.id === stateId) ?? labStates[0]!;
}

export function appendStateSelector(
  selector: string,
  stateId: LabStateId,
): string {
  const suffix = stateDefinition(stateId).selectorSuffix;
  if (!suffix) return selector;
  return selector
    .split(",")
    .map((part) => appendBeforePseudoElement(part.trim(), suffix))
    .join(", ");
}

function appendBeforePseudoElement(selector: string, suffix: string): string {
  const pseudoIndex = selector.indexOf("::");
  return pseudoIndex < 0
    ? `${selector}${suffix}`
    : `${selector.slice(0, pseudoIndex)}${suffix}${selector.slice(pseudoIndex)}`;
}

