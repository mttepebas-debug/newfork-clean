#!/usr/bin/env node
/**
 * AVATAR-IKON: the drawing archive's one generator.
 *
 * The single committed input is scripts/lineup-art/archive.json: one entry per drawing (number, key,
 * name, kind, style, the jobs it suits, its SVG). Every file below is derived from it; none is edited
 * by hand:
 *   - packages/shared/src/lineup-art.generated.ts   the keys and what is known of each drawing (no SVG)
 *   - apps/web/src/lineup-art/art-svgs.generated.ts  the SVGs, loaded only through useLineupArt.ts's
 *                                                    import(), so they ship as their own chunk
 *   - supabase/tests/lineup_art_parity.test.sql     the database's suggestion rule answers as the
 *                                                    shared one does, for 30 job names
 *   - the insert block of the archive migration      between `-- lineup-art:begin` / `-- lineup-art:end`
 *     (ARCHIVE_MIGRATION below)                      in that migration; nothing else in it is touched
 *
 * The parity test's expected answers come from the shared rule itself
 * (packages/shared/src/lineup-art-rule.ts, run here through Node's type stripping), not from a copy.
 *
 * Usage (from the repository root):
 *   node scripts/lineup-art/gen.mjs                      write every generated file
 *   node scripts/lineup-art/gen.mjs --check              write nothing; exit 1 naming each stale file
 *   node scripts/lineup-art/gen.mjs --import <icons.js>  rebuild archive.json from the avatar page's
 *                                                        icons.js (window.ICONS=[…]), then write
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");

const ARCHIVE = "scripts/lineup-art/archive.json";
const SHARED_OUT = "packages/shared/src/lineup-art.generated.ts";
const WEB_OUT = "apps/web/src/lineup-art/art-svgs.generated.ts";
const PARITY_OUT = "supabase/tests/lineup_art_parity.test.sql";
const RULE = "packages/shared/src/lineup-art-rule.ts";
/**
 * The migration that fills app_private.lineup_art (Task 1.3 creates it). null until then; once named,
 * the file must exist and hold the two marker lines.
 */
const ARCHIVE_MIGRATION = null;
const BEGIN = "-- lineup-art:begin";
const END = "-- lineup-art:end";

const HEADER = "// Generated by scripts/lineup-art/gen.mjs — do not edit.";
const SQL_HEADER = "-- Generated by scripts/lineup-art/gen.mjs — do not edit.";

// The parity test's fixed names; 15 more come from the archive's own job words.
const FIXED_NAMES = [
  "Server",
  "Bartender",
  "Line Cook",
  "Host",
  "Dishwasher",
  "Barista",
  "General Manager",
  "Owner",
  "Prep Cook",
  "Busser",
  "Food Runner",
  "Sous Chef",
  "Expo",
  "Cashier",
  "Delivery Driver",
];
const ARCHIVE_NAMES = 15;

const KINDS = new Map([
  ["obj", "object"],
  ["person", "person"],
  ["team", "team"],
]);
const STYLES = new Set(["line", "color"]);
const KEY = /^\d{3}-[a-z0-9-]+$/;

const abs = (rel) => path.join(root, rel);
const read = (rel) => (fs.existsSync(abs(rel)) ? fs.readFileSync(abs(rel), "utf8") : null);

/** The avatar page's icons.js → archive entries (kinds named as the product names them). */
function importIcons(file) {
  const text = fs.readFileSync(file, "utf8").trim();
  const prefix = "window.ICONS=";
  if (!text.startsWith(prefix)) throw new Error(`${file}: does not start with ${prefix}`);
  const icons = JSON.parse(text.slice(prefix.length).replace(/;\s*$/, ""));
  return icons.map((icon) => {
    const kind = KINDS.get(icon.kind);
    if (!kind) throw new Error(`${icon.id}: unknown kind ${icon.kind}`);
    const jobs =
      kind === "team"
        ? []
        : [...new Set(String(icon.jobs).split(",").map((job) => job.trim().toLowerCase()).filter(Boolean))];
    return { no: icon.no, key: icon.id, name: icon.name, kind, style: icon.style, jobs, svg: icon.svg.replace(/\r/g, "") };
  });
}

function validate(items) {
  const keys = new Set();
  items.forEach((item, index) => {
    const where = `${ARCHIVE} entry ${index + 1}`;
    if (item.no !== index + 1) throw new Error(`${where}: no ${item.no}, expected ${index + 1} (entries stay in number order)`);
    if (!KEY.test(item.key)) throw new Error(`${where}: key ${item.key}`);
    if (keys.has(item.key)) throw new Error(`${where}: key ${item.key} twice`);
    keys.add(item.key);
    if (![...KINDS.values()].includes(item.kind)) throw new Error(`${where}: kind ${item.kind}`);
    if (!STYLES.has(item.style)) throw new Error(`${where}: style ${item.style}`);
    if (typeof item.name !== "string" || !item.name.trim()) throw new Error(`${where}: no name`);
    if (!Array.isArray(item.jobs) || item.jobs.some((job) => job !== job.trim().toLowerCase() || !job))
      throw new Error(`${where}: jobs must be lower case and trimmed`);
    if ((item.kind === "team") !== (item.jobs.length === 0)) throw new Error(`${where}: only team drawings have no jobs`);
    if (!/^<svg[\s>]/.test(item.svg) || !item.svg.endsWith("</svg>")) throw new Error(`${where}: svg`);
  });
  return items;
}

const js = (value) => JSON.stringify(value);
const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sqlArray = (values) => `'{${values.join(",")}}'::text[]`;

function sharedFile(items) {
  const keys = items.map((item) => `  ${js(item.key)},`).join("\n");
  const rows = items
    .map(
      (item) =>
        `  { key: ${js(item.key)}, no: ${item.no}, name: ${js(item.name)}, jobs: [${item.jobs.map(js).join(", ")}], kind: ${js(item.kind)}, style: ${js(item.style)} },`,
    )
    .join("\n");
  return `${HEADER}
// Source: ${ARCHIVE}. The drawings themselves are in apps/web/src/lineup-art/art-svgs.generated.ts.
import type { LineupArtItem } from "./lineup-art-rule";

export const lineupArtKeys = [
${keys}
] as const;

export const lineupArtItems: readonly LineupArtItem[] = [
${rows}
];
`;
}

function webFile(items) {
  const rows = items.map((item) => `  ${js(item.key)}: ${js(item.svg)},`).join("\n");
  return `${HEADER}
// Source: ${ARCHIVE}. Only useLineupArt.ts loads this, through import(), so it ships as its own chunk.
export const artSvgs: Record<string, string> = {
${rows}
};
`;
}

const titleCase = (words) => words.replace(/(^|[\s(-])([a-z])/g, (_, before, letter) => before + letter.toUpperCase());

/** The 30 names: the fixed 15, then 15 of the archive's job words spread over its sorted list. */
function parityNames(items) {
  const fixed = new Set(FIXED_NAMES.map((name) => name.toLowerCase()));
  const pool = [...new Set(items.flatMap((item) => item.jobs))].filter((job) => !fixed.has(job)).sort();
  if (pool.length < ARCHIVE_NAMES) throw new Error(`only ${pool.length} archive job words for the parity test`);
  const picked = Array.from({ length: ARCHIVE_NAMES }, (_, index) => pool[Math.floor((index * pool.length) / ARCHIVE_NAMES)]);
  return [...FIXED_NAMES, ...picked.map(titleCase)];
}

function parityFile(items, suggest) {
  const names = parityNames(items);
  const lines = names.map(
    (name) => `select is(app_private.suggest_lineup_art(${sql(name)}), ${sqlArray(suggest(items, name))}, ${sql(`${name}: same drawings as the shared rule`)});`,
  );
  return `begin;
create extension if not exists pgtap with schema extensions;
select plan(${names.length});

${SQL_HEADER}
-- Source: ${ARCHIVE}; expected answers from ${RULE}.
-- AVATAR-IKON: the database owns the suggestion rule (app_private.suggest_lineup_art); the web's
-- "New job" preview runs the shared copy. For each name both give the same drawings, in the same order.

${lines.join("\n")}

select * from finish();
rollback;
`;
}

function migrationBlock(items) {
  const rows = items.map(
    (item) => `  (${sql(item.key)}, ${item.no}, ${sql(item.kind)}, ${sql(item.style)}, array[${item.jobs.map(sql).join(", ")}]::text[])`,
  );
  return `insert into app_private.lineup_art (key, no, kind, style, jobs) values\n${rows.join(",\n")};\n`;
}

function withMigrationBlock(text, items) {
  const begin = text.indexOf(`${BEGIN}\n`);
  const end = text.indexOf(END, begin + 1);
  if (begin < 0 || end < 0 || text.indexOf(BEGIN, begin + 1) >= 0)
    throw new Error(`${ARCHIVE_MIGRATION}: needs one "${BEGIN}" line and one "${END}" line after it`);
  return text.slice(0, begin + BEGIN.length + 1) + migrationBlock(items) + text.slice(end);
}

async function outputs(items) {
  const { suggestLineupArtFrom } = await import(pathToFileURL(abs(RULE)).href);
  const files = new Map([
    [SHARED_OUT, sharedFile(items)],
    [WEB_OUT, webFile(items)],
    [PARITY_OUT, parityFile(items, suggestLineupArtFrom)],
  ]);
  if (ARCHIVE_MIGRATION) {
    const text = read(ARCHIVE_MIGRATION);
    if (text === null) throw new Error(`${ARCHIVE_MIGRATION}: named in gen.mjs but missing`);
    files.set(ARCHIVE_MIGRATION, withMigrationBlock(text, items));
  }
  return files;
}

async function main(argv) {
  const check = argv.includes("--check");
  const at = argv.indexOf("--import");
  if (check && at >= 0) throw new Error("--check and --import do not go together");

  if (at >= 0) {
    const source = argv[at + 1];
    if (!source) throw new Error("--import needs the path to icons.js");
    const items = validate(importIcons(path.resolve(source)));
    fs.writeFileSync(abs(ARCHIVE), `${JSON.stringify(items, null, 2)}\n`);
    console.log(`lineup-art: ${ARCHIVE} rebuilt from ${source} (${items.length} drawings)`);
  }

  const archive = read(ARCHIVE);
  if (archive === null) throw new Error(`${ARCHIVE} is missing`);
  const items = validate(JSON.parse(archive));
  const files = await outputs(items);

  if (check) {
    const stale = [...files].filter(([rel, text]) => read(rel) !== text).map(([rel]) => rel);
    if (stale.length) {
      for (const rel of stale) console.log(`stale: ${rel}`);
      console.log("Run node scripts/lineup-art/gen.mjs to rewrite them.");
      return 1;
    }
    console.log(`lineup-art: ${files.size} generated files are current`);
    return 0;
  }

  for (const [rel, text] of files) {
    if (read(rel) === text) continue;
    fs.mkdirSync(path.dirname(abs(rel)), { recursive: true });
    fs.writeFileSync(abs(rel), text);
    console.log(`wrote ${rel}`);
  }
  return 0;
}

main(process.argv.slice(2)).then(
  (code) => process.exit(code),
  (error) => {
    console.error(`lineup-art: ${error.message}`);
    process.exit(2);
  },
);
