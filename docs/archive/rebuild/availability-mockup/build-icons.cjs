const { createRequire } = require('node:module');
const { writeFileSync, copyFileSync } = require('node:fs');
const path = require('node:path');
const req = createRequire(path.resolve(__dirname, '../../../apps/web/package.json'));
const React = req('react');
const { renderToStaticMarkup } = req('react-dom/server');
const lucide = req('lucide-react');
const names = ['CalendarDays','Users','Settings','Bell','LogOut','ChevronDown','ChevronRight','ArrowLeft','ArrowRight','ArrowRightLeft','Check','Plus','X','Info','Clock','Shield','Copy','Trash2','RotateCcw','Save','MessageSquare','LockKeyhole','Search','TriangleAlert','LayoutGrid','CalendarOff','Send','History','BriefcaseBusiness','MapPin','Pencil','Menu'];
const icons = Object.fromEntries(names.map(n => [n, renderToStaticMarkup(React.createElement(lucide[n], {size:16,strokeWidth:1.7,'aria-hidden':true}))]));
writeFileSync(path.join(__dirname,'icons.js'), 'window.ICONS = '+JSON.stringify(icons)+';\n');
copyFileSync(path.resolve(__dirname,'../../../apps/web/public/favicon.svg'),path.join(__dirname,'brand.svg'));
